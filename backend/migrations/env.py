"""Alembic environment wired to the app's settings and model metadata."""

import re
from logging.config import fileConfig

from alembic import context
from sqlalchemy import engine_from_config, pool
from sqlalchemy.schema import SchemaItem

from app.config import get_settings
from app.models import Base

config = context.config
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

config.set_main_option("sqlalchemy.url", get_settings().database_url.replace("%", "%%"))
target_metadata = Base.metadata

# The weekly partitions of the events table, which the app makes and drops as events come and go.
_PARTITION = re.compile(r"^events_p\d{8}$")


def include_object(
    _object: SchemaItem, name: str | None, type_: str, _reflected: bool, _compare_to: object
) -> bool:
    """Leaves the partitions out of the comparison, so `alembic check` doesn't ask for them to be
    dropped and an autogenerated migration never does."""
    return not (type_ == "table" and name is not None and _PARTITION.match(name))


def run_migrations_offline() -> None:
    context.configure(
        url=config.get_main_option("sqlalchemy.url"),
        target_metadata=target_metadata,
        include_object=include_object,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    with connectable.connect() as connection:
        context.configure(
            connection=connection, target_metadata=target_metadata, include_object=include_object
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
